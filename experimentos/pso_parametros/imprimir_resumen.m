function imprimir_resumen(prueba, est)
%IMPRIMIR_RESUMEN  Muestra en consola el resultado de una prueba.
%
%   IMPRIMIR_RESUMEN(prueba, est) imprime una línea con los parámetros de la
%   prueba y sus métricas principales, para seguir el avance del script.

    fprintf(['  %s (%-22s) w=%.3f c1=%.3f c2=%.3f | mejor=%.6g  ' ...
             'prom=%.6g  error=%.3g  éxito=%5.1f%%  iter=%s\n'], ...
        prueba.nombre, prueba.desc, prueba.w, prueba.c1, prueba.c2, ...
        est.mejor_valor, est.promedio, est.error_promedio, est.tasa_exito, ...
        num2str(est.iter_convergencia, '%.1f'));
end
