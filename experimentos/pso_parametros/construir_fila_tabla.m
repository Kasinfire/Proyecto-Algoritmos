function fila = construir_fila_tabla(problema, prueba, est)
%CONSTRUIR_FILA_TABLA  Convierte los resultados de una prueba en una fila de tabla.
%
%   fila = CONSTRUIR_FILA_TABLA(problema, prueba, est) devuelve una tabla de
%   una sola fila; main_pso concatena todas las filas al final.
%
%   Entradas:
%       problema - Función evaluada.
%       prueba  - Parámetros usados (w, c1, c2).
%       est     - Estadísticas de calcular_estadisticas().

    fila = table( ...
        string(problema.nombre), string(prueba.nombre), string(prueba.desc), ...
        prueba.w, prueba.c1, prueba.c2, ...
        string(mat2str(est.mejor_posicion, 4)), ...
        est.mejor_valor, est.promedio, est.desv_estandar, est.error_promedio, ...
        est.tasa_exito, est.iter_convergencia, ...
        'VariableNames', {'funcion', 'prueba', 'descripcion', ...
                          'w', 'c1', 'c2', 'mejor_posicion', ...
                          'mejor_valor', 'promedio', 'desv_estandar', ...
                          'error_promedio', 'tasa_exito_pct', 'iter_convergencia'});
end
