function defs = parametros_aco(representacion)
% PARAMETROS_ACO  Parametros ACO pertinentes para la representacion dada.

    if ~ismember(representacion, {'binario', 'permutacion'})
        error('parametros_aco:representacion', ...
            'ACO no soporta la representacion "%s".', representacion);
    end

    defs = [parametros_comunes(), ...
        crear_parametro('n_hormigas', 'Numero de hormigas', 'entero', 30, ...
            min=2, max=1000, descripcion='Soluciones construidas en cada iteracion.'), ...
        crear_parametro('evaporacion', 'Evaporacion', 'real', 0.2, ...
            min=0.01, max=0.99, descripcion='Fraccion de feromona que se pierde por iteracion.')];

    if strcmp(representacion, 'binario')
        defs = [defs, crear_parametro('probabilidad_inicial', 'Probabilidad inicial de bit', ...
            'real', 0.5, min=0.01, max=0.99, ...
            descripcion='Probabilidad inicial de que una hormiga active cada bit.')];
    else
        defs = [defs, ...
            crear_parametro('feromona_inicial', 'Feromona inicial', 'real', 1, ...
                min=0.001, max=1000, descripcion='Nivel inicial de feromona por arista.'), ...
            crear_parametro('Q', 'Deposito de feromona (Q)', 'real', 1, ...
                min=0.001, max=1000, descripcion='Escala del deposito de la mejor solucion.'), ...
            crear_parametro('alfa', 'Importancia de feromona (alfa)', 'real', 1, ...
                min=0, max=10, descripcion='Peso de la feromona al elegir la siguiente ciudad.'), ...
            crear_parametro('beta', 'Importancia heuristica (beta)', 'real', 2, ...
                min=0, max=10, descripcion='Peso de la distancia inversa, si hay distancias disponibles.')];
    end
end
