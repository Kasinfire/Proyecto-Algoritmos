function defs = parametros_ais(representacion)
% PARAMETROS_AIS  Parametros de CLONALG para la representacion dada.

    if ~ismember(representacion, {'continuo', 'binario', 'permutacion'})
        error('parametros_ais:representacion', ...
            'AIS no soporta la representacion "%s".', representacion);
    end

    defs = [parametros_comunes(), ...
        crear_parametro('n_anticuerpos', 'Numero de anticuerpos', 'entero', 40, ...
            min=4, max=1000, descripcion='Tamano de la poblacion inmune.'), ...
        crear_parametro('n_seleccionados', 'Anticuerpos seleccionados', 'entero', 10, ...
            min=1, max=500, descripcion='Numero de mejores anticuerpos que se clonan.'), ...
        crear_parametro('n_clones', 'Clones por anticuerpo seleccionado', 'entero', 5, ...
            min=1, max=100, descripcion='Factor que determina el numero de clones por rango.'), ...
        crear_parametro('tasa_mutacion', 'Tasa maxima de mutacion', 'real', 0.2, ...
            min=0, max=1, descripcion='Probabilidad maxima de mutar cada componente.'), ...
        crear_parametro('n_reemplazo', 'Anticuerpos a reemplazar', 'entero', 4, ...
            min=0, max=500, descripcion='Cantidad de peores anticuerpos sustituidos por soluciones nuevas.')];

    if strcmp(representacion, 'continuo')
        defs = [defs, crear_parametro('sigma_mutacion', 'Escala de mutacion', 'real', 0.1, ...
            min=0, max=1, descripcion='Desviacion gaussiana como fraccion del rango de busqueda.')];
    end
end
