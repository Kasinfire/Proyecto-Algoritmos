function defs = parametros_ga(representacion)
% PARAMETROS_GA  Parametros del GA pertinentes para la representacion dada.
%
%   defs = parametros_ga('continuo')
%   params = valores_por_defecto(parametros_ga('binario'))

    defs = [parametros_comunes(), ...
        crear_parametro('tam_poblacion', 'Tamano de poblacion', 'entero', 60, ...
            min=4, max=1000, descripcion='Numero de individuos por generacion.'), ...
        crear_parametro('tasa_cruza', 'Tasa de cruza', 'real', 0.9, ...
            min=0, max=1, descripcion='Probabilidad de cruzar cada pareja de padres.'), ...
        crear_parametro('seleccion', 'Metodo de seleccion', 'opcion', 'torneo', ...
            opciones={'torneo', 'ruleta'}, descripcion=['Torneo: gana el mejor de k ' ...
            'individuos al azar. Ruleta: probabilidad proporcional a la calidad.']), ...
        crear_parametro('k_torneo', 'Tamano del torneo (k)', 'entero', 3, ...
            min=2, max=20, descripcion=['Individuos que compiten en cada torneo. ' ...
            'Solo se usa con seleccion por torneo.']), ...
        crear_parametro('n_elite', 'Individuos elite', 'entero', 2, ...
            min=0, max=100, descripcion=['Mejores padres que pasan intactos a la ' ...
            'siguiente generacion. 0 = sin elitismo.'])];

    switch representacion
        case 'continuo'
            defs = [defs, ...
                crear_parametro('tipo_cruza', 'Cruza', 'opcion', 'blx', ...
                    opciones={'blx', 'aritmetica'}, descripcion=['BLX-alfa: hijo al azar ' ...
                    'en el intervalo de los padres ampliado. Aritmetica: combinacion convexa.']), ...
                crear_parametro('alpha_blx', 'Alfa de BLX', 'real', 0.3, ...
                    min=0, max=1, descripcion='Cuanto se amplia el intervalo de los padres en BLX-alfa.'), ...
                crear_parametro('tasa_mutacion', 'Tasa de mutacion (por gen)', 'real', 0.2, ...
                    min=0, max=1, descripcion='Probabilidad de mutar cada variable de cada hijo.'), ...
                crear_parametro('sigma_ini', 'Sigma inicial', 'real', 0.10, ...
                    min=0, max=1, descripcion=['Desviacion de la mutacion gaussiana al ' ...
                    'inicio, como fraccion del rango de cada variable.']), ...
                crear_parametro('sigma_fin', 'Sigma final', 'real', 0.005, ...
                    min=0, max=1, descripcion=['Desviacion de la mutacion gaussiana en la ' ...
                    'ultima generacion; baja linealmente desde sigma_ini.'])];
        case 'binario'
            defs = [defs, ...
                crear_parametro('tipo_cruza', 'Cruza', 'opcion', 'un_punto', ...
                    opciones={'un_punto', 'uniforme'}, descripcion=['Un punto: se corta el ' ...
                    'vector una vez. Uniforme: cada bit viene de un padre al azar.']), ...
                crear_parametro('tasa_mutacion', 'Tasa de mutacion (por bit)', 'real', 0.02, ...
                    min=0, max=1, descripcion='Probabilidad de invertir cada bit de cada hijo.')];
        case 'permutacion'
            defs = [defs, ...
                crear_parametro('tipo_mutacion', 'Mutacion', 'opcion', 'swap', ...
                    opciones={'swap', 'inversion'}, descripcion=['Swap: intercambia dos ' ...
                    'posiciones. Inversion: invierte un tramo de la ruta.']), ...
                crear_parametro('tasa_mutacion', 'Tasa de mutacion (por individuo)', 'real', 0.2, ...
                    min=0, max=1, descripcion='Probabilidad de mutar cada hijo (la cruza siempre es OX).')];
        otherwise
            error('parametros_ga:representacion', ...
                  'GA no soporta la representacion "%s".', representacion);
    end
end
