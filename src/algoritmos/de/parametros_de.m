function defs = parametros_de(representacion)
% PARAMETROS_DE  Parametros de DE pertinentes para la representacion dada.
%
%   defs = parametros_de('continuo')
%   params = valores_por_defecto(parametros_de('permutacion'))
%
%   Los parametros son los mismos en las tres representaciones: en binario y
%   permutacion DE trabaja en un espacio continuo [0, 1] y decodifica.

    switch representacion
        case {'continuo', 'binario', 'permutacion'}
        otherwise
            error('parametros_de:representacion', ...
                  'DE no soporta la representacion "%s".', representacion);
    end

    defs = [parametros_comunes(), ...
        crear_parametro('tam_poblacion', 'Tamano de poblacion', 'entero', 50, ...
            min=4, max=1000, descripcion=['Numero de vectores. Minimo 4: la mutacion ' ...
            'necesita tres vectores distintos al objetivo.']), ...
        crear_parametro('factor_f', 'Factor de mutacion (F)', 'real', 0.5, ...
            min=0, max=2, descripcion=['Escala la diferencia entre vectores. Alto = pasos ' ...
            'grandes (exploracion), bajo = pasos chicos (explotacion).']), ...
        crear_parametro('tasa_cr', 'Tasa de cruza (CR)', 'real', 0.9, ...
            min=0, max=1, descripcion=['Probabilidad de tomar cada gen del vector mutante. ' ...
            'Siempre se toma al menos uno.']), ...
        crear_parametro('estrategia', 'Estrategia', 'opcion', 'rand/1/bin', ...
            opciones={'rand/1/bin', 'best/1/bin'}, descripcion=['rand/1/bin: base ' ...
            'aleatoria, explora mas. best/1/bin: base en el mejor vector, converge mas rapido.'])];
end
