function defs = parametros_pso(representacion)
% PARAMETROS_PSO  Parametros del PSO pertinentes para la representacion dada.
%
%   defs = parametros_pso('continuo')
%   params = valores_por_defecto(parametros_pso('binario'))

    defs = [parametros_comunes(), ...
        crear_parametro('n_particulas', 'Numero de particulas', 'entero', 30, ...
            min=2, max=1000, descripcion='Tamano del enjambre.'), ...
        crear_parametro('w', 'Inercia (w)', 'real', 0.7, ...
            min=0, max=1.5, descripcion=['Cuanto conserva la particula su velocidad. ' ...
            'Alta = mas exploracion, baja = mas explotacion.']), ...
        crear_parametro('c1', 'Coeficiente cognitivo (c1)', 'real', 1.5, ...
            min=0, max=4, descripcion='Atraccion hacia la mejor posicion propia (pbest).'), ...
        crear_parametro('c2', 'Coeficiente social (c2)', 'real', 1.5, ...
            min=0, max=4, descripcion='Atraccion hacia la mejor posicion del enjambre (gbest).')];

    switch representacion
        case {'continuo', 'permutacion'}
            defs = [defs, crear_parametro('fraccion_vmax', 'Velocidad maxima', 'real', 0.2, ...
                min=0.01, max=1, descripcion=['Velocidad maxima como fraccion del rango ' ...
                'de cada variable: vmax = fraccion * (ub - lb).'])];
        case 'binario'
            defs = [defs, crear_parametro('vmax', 'Velocidad maxima', 'real', 4, ...
                min=0.5, max=10, descripcion=['Limite de la velocidad; con sigmoide(4) ~ 0.98 ' ...
                'un bit nunca queda fijo del todo.'])];
        otherwise
            error('parametros_pso:representacion', ...
                  'PSO no soporta la representacion "%s".', representacion);
    end
end
